const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const html = fs.readFileSync('index.html', 'utf8');
const demo = fs.readFileSync('legacy-demo.html', 'utf8');
test('responsive viewport', () => assert.match(html, /name="viewport"/));
test('demo disclaimer', () => assert.match(demo, /DEMO • NO LIVE ODDS/));
test('unverified sportsbook handoff disabled', () => assert.match(demo, /<button disabled[^>]*>Send to FanDuel/));
test('touchdown lab present', () => assert.match(demo, /Touchdown Lab/));
test('betslip present', () => assert.match(demo, /My Betslip/));
test('no direct odds provider browser calls', () => assert.doesNotMatch(html, /api\.the-odds-api\.com/));
